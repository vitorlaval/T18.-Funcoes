
// 1) O que são funções?
// Funções são blocos de códigos que realizam uma tarefa
// específica e podem ser utilizados várias vezes no programa.


// 2) O que uma função retorna quando não usa o comando return?
// Quando uma função não utiliza o comando return,
// ela retorna NULL, ou seja, não devolve nenhum valor específico.


// 3) Qual é a função chr?
// A função chr() transforma um número correspondente
// a um código ASCII em um caractere.
// Exemplo: chr(65) retorna a letra A.


// 4) O que são funções nativas?
// São funções que já vêm prontas na linguagem PHP
// e podem ser utilizadas sem precisar criá-las.
// Exemplos: strlen(), date() e strtoupper().


// 5) O que são funções ambiente?
// São funções utilizadas para acessar informações
// do ambiente onde o PHP está sendo executado.
// Um exemplo é a função getenv().

